        f.write("4. Default quotas will be assigned:\\n")
        f.write("   - CPU: 20 cores\\n")
        f.write("   - RAM: 64 GB\\n")
        f.write("   - GPU: 2 units\\n")
        f.write("5. Organization status changes to ACTIVE\\n\\n")
        
        f.write("### Viewing Organization Hierarchy\\n\\n")
        f.write("1. Click on an organization card to expand\\n")
        f.write("2. View assigned quotas (CPU, RAM, GPU)\\n")
        f.write("3. See all projects under the organization\\n\\n")
        
        f.write("---\\n\\n")
        
        f.write("## 📦 Managing Projects\\n\\n")
        f.write("### Deploying a New Project\\n\\n")
        f.write("1. Expand an organization card\\n")
        f.write("2. Click **\"Deploy Project\"** button\\n")
        f.write("3. A new project will be created with:\\n")
        f.write("   - Random project name\\n")
        f.write("   - Physical folder structure\\n")
        f.write("   - Database record\\n")
        f.write("4. Project appears in the organization's project list\\n\\n")
        
        f.write("### Viewing Project Status\\n\\n")
        f.write("- Each project shows:\\n")
