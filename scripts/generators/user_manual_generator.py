import os
from datetime import datetime

def generate_user_manual(root_dir, output_dir):
    """사용자 매뉴얼 생성"""
    
    # Super Admin 매뉴얼
    admin_file = os.path.join(output_dir, "SUPER_ADMIN_MANUAL.md")
    
    with open(admin_file, 'w', encoding='utf-8') as f:
        f.write("# 👑 Super Admin Manual\n\n")
        f.write(f"> **Last Updated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\\n\\n")
        
        f.write("---\\n\\n")
        
        f.write("## 📋 Overview\\n\\n")
        f.write("Super Admin Console을 사용하여 전체 플랫폼을 관리하는 방법을 안내합니다.\\n\\n")
        
        f.write("---\\n\\n")
        
        f.write("## 🚀 Getting Started\\n\\n")
        f.write("### Accessing the Dashboard\\n\\n")
        f.write("1. Navigate to `http://localhost:3001/admin`\\n")
        f.write("2. Login with Super Admin credentials\\n")
        f.write("3. You will see the Super Admin Engine dashboard\\n\\n")
        
        f.write("---\\n\\n")
        
        f.write("## 🏗️ Managing Clusters\\n\\n")
