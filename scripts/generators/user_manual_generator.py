        f.write("   - RAM: 4096 GB\\n")
        f.write("   - GPU: 64 units\\n")
        f.write("3. A success toast notification will appear\\n")
        f.write("4. The new cluster will appear in the hierarchy view\\n\\n")
        
        f.write("### Viewing Cluster Details\\n\\n")
        f.write("- Each cluster card shows:\\n")
        f.write("  - Cluster name\\n")
        f.write("  - Region (e.g., kr-seoul-1)\\n")
        f.write("  - Status (ACTIVE, MAINTENANCE, DOWN)\\n")
        f.write("  - Number of organizations\\n\\n")
        
        f.write("---\\n\\n")
        
        f.write("## 🏢 Managing Organizations\\n\\n")
        f.write("### Approving Organizations\\n\\n")
        f.write("1. Check the **\"Pending Approval\"** section\\n")
        f.write("2. Review organization details:\\n")
        f.write("   - Organization name\\n")
        f.write("   - Requested tier (Enterprise, Pro, etc.)\\n")
        f.write("   - Region preference\\n")
