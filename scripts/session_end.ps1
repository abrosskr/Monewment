---

## 📝 메모

- Smart Commit 스크립트 사용: ``.\scripts\smart_commit.ps1 -Message "your message"``
- 문서 생성: ``python scripts/generate_docs_v4.py``
- 실시간 감시: ``python scripts/watch_and_doc.py``

---

*Auto-generated by session_end.ps1*
"@

Set-Content -Path $nextActionsFile -Value $nextActions
Write-Host "  ✅ NEXT_ACTIONS.md created" -ForegroundColor Green

# 6. 자동 커밋
Write-Host "`n💾 Committing session updates..." -ForegroundColor Yellow
git add docs/masterplan.md docs/NEXT_ACTIONS.md 2>$null

$hasChanges = -not (git diff --quiet --staged 2>$null)
if ($hasChanges) {
    git commit -m "chore: session end - auto-update masterplan and next actions

Session: $SessionSummary
Commits: $commitCount
Progress: $progress%"
    
    git push origin feature/software-first-infra
    Write-Host "  ✅ Changes committed and pushed" -ForegroundColor Green
} else {
    Write-Host "  ℹ️  No changes to commit" -ForegroundColor Gray
}

# 완료 메시지
Write-Host "`n" + ("=" * 60)
Write-Host "🎉 Session End Complete!" -ForegroundColor Green
Write-Host ("=" * 60)
Write-Host "`nUpdated files:" -ForegroundColor Cyan
Write-Host "  📋 docs/masterplan.md" -ForegroundColor Gray
Write-Host "  🎯 docs/NEXT_ACTIONS.md" -ForegroundColor Gray
Write-Host "`nNext time you start, check NEXT_ACTIONS.md for your todo list!" -ForegroundColor Yellow
Write-Host "`n👋 See you next time!" -ForegroundColor Cyan
